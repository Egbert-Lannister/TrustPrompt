"""R16 item 2: conformal low-trust thresholds per dataset (calibration = train-holdout real images),
checked on val. Writes results/<output>.json and docs/conformal_results.md.

  python -m scripts.conformal_threshold --data cache/trust_data_v1_nyu cache/trust_data_v1_hammer \
      --cache "cache/trust_t_v1_real_sim_nofeat_{tag}_dev_v1" --output results/trust_t_v1_crc
"""
import argparse

import numpy as np

from scripts.train_trust import load_items
from scripts.trust_mask_diagnostics import TAGS
from tp.provenance import ROOT, sha256, write_json
from tp.trust.cache import TrustCache
from tp.trust.conformal import GRID, crc_threshold, image_losses
from tp.trust.data import scene_inner_holdout


def collect(items, cache, tau=0.05):
    L, F, N, scenes = [], [], [], []
    for e in items:
        a = np.load(e["file"]); a = {k: a[k] for k in a.files}
        t = np.load(cache.root / cache.index[f"{e['sensor']}__{e['scene']}__{e['frame']}"]["path"])["trust"].astype(np.float32)
        l, f, n = image_losses(t, a, tau=tau)
        L.append(l); F.append(f); N.append(n); scenes.append(e["scene"])
    return np.array(L), np.array(F), np.array(N), scenes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", nargs="+", required=True); ap.add_argument("--cache", required=True)
    ap.add_argument("--alphas", nargs="+", type=float, default=[0.05, 0.1, 0.2]); ap.add_argument("--output", required=True)
    ap.add_argument("--danger-tau", type=float, default=0.05, help="far-contaminated = P > (1 + tau) GT")
    ap.add_argument("--doc", default="docs/conformal_results.md")
    a = ap.parse_args()
    items = [e for e in load_items(a.data)[0] if e["variant"] == "real"]
    out = dict(danger_tau=a.danger_tau, definition="loss = unflagged share of far-contaminated main-scope prompt pixels (P > (1+danger_tau) GT); "
                          "CRC bound n/(n+1) R + 1/(n+1) <= alpha; calibration = train-holdout scenes; check = val; 192x256 grid",
               datasets={})
    lines = [f"# Conformal low-trust thresholds (R16 item 2), danger = P > {1 + a.danger_tau:.2f}·GT", "",
             "Generated by `python -m scripts.conformal_threshold`. Loss per image = share of far-contaminated main-scope "
             "prompt pixels (P > (1+τ_d)·GT) left unflagged. λ̂ from train-holdout scenes (calibration); the val split checks "
             "the guarantee. Exchangeability between calibration and val scenes is assumed, not shown (HAMMER: scene 10 vs 11). "
             "Grid 192×256.", ""]
    for ds, tag in TAGS.items():
        c = TrustCache(a.cache.replace("{tag}", tag))
        cal = [e for e in items if e["dataset"] == ds and e["split"] == "train" and scene_inner_holdout(ds, e["scene"])]
        val = [e for e in items if e["dataset"] == ds and e["split"] == "val"]
        Lc, Fc, Nc, _ = collect(cal, c, a.danger_tau); Lv, Fv, Nv, _ = collect(val, c, a.danger_tau)
        res = dict(cache=str(c.root), cache_receipt_sha256=sha256(c.root / "receipt.json"), model_threshold=c.threshold,
                   calibration_images=len(cal), calibration_images_with_far=int((Nc > 0).sum()),
                   val_images=len(val), val_images_with_far=int((Nv > 0).sum()), alphas={})
        k0 = int(np.argmin(np.abs(GRID - c.threshold)))
        lines += [f"## {ds}", "", f"Calibration {len(cal)} images ({int((Nc > 0).sum())} with far contamination); val {len(val)} "
                  f"({int((Nv > 0).sum())}). Model threshold {c.threshold}: val risk {Lv[:, k0].mean():.3f}, "
                  f"val false flags {Fv[:, k0].mean():.3f}.", "",
                  "| α | λ̂ | calibration bound | val risk (mean loss) | val risk ≤ α | val false flags | val images with loss > α |",
                  "|---:|---:|---:|---:|---|---:|---:|"]
        for al in a.alphas:
            lam, bnd = crc_threshold(Lc, al)
            if lam is None:
                res["alphas"][str(al)] = dict(lambda_hat=None, best_bound=bnd)
                lines.append(f"| {al} | none (best bound {bnd:.3f}) | | | | | |"); continue
            k = int(np.flatnonzero(GRID == lam)[0])
            vr, vf = float(Lv[:, k].mean()), float(Fv[:, k].mean())
            res["alphas"][str(al)] = dict(lambda_hat=lam, calibration_bound=bnd, val_risk=vr, val_false_flags=vf,
                                          val_risk_le_alpha=vr <= al, val_share_images_loss_gt_alpha=float((Lv[:, k] > al).mean()))
            lines.append(f"| {al} | {lam:.3f} | {bnd:.3f} | {vr:.3f} | {'yes' if vr <= al else 'NO'} | {vf:.3f} | "
                         f"{(Lv[:, k] > al).mean():.2f} |")
        lines.append("")
        res["model_threshold_val"] = dict(risk=float(Lv[:, k0].mean()), false_flags=float(Fv[:, k0].mean()))
        out["datasets"][ds] = res
        print(ds, res["alphas"], flush=True)
    write_json(ROOT / f"{a.output}.json" if not a.output.startswith("/") else f"{a.output}.json", out)
    (ROOT / a.doc).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
