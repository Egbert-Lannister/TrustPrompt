"""Low-trust mask quality on the 192x256 grid, out-of-fit populations only.

  python -m scripts.trust_mask_diagnostics --data cache/trust_data_v1_nyu cache/trust_data_v1_hammer \
      --caches v0_real=cache/trust_t_v0_real_{tag}_dev_v1 v1_real=cache/trust_t_v1_real_{tag}_dev_v1 ...

`{tag}` is replaced by nyu / hammer. For every real item of the val split and of the train-holdout
scenes: recall = flagged share of contaminated prompt pixels inside the main scope (NYU mirror /
HAMMER object) and over the whole image; false flags = flagged share of clean prompt pixels.
Gate (|P - D_g| / D_g > 0.05, same D_g as the arrays) is the reference. Image means, then dataset.
"""
import argparse
import json

import numpy as np

from scripts.train_trust import load_items
from tp.provenance import ROOT, write_json
from tp.trust.cache import TrustCache
from tp.trust.data import scene_inner_holdout

TAGS = {"mirror3d_nyu": "nyu", "hammer": "hammer"}


def masks_for(a, flag):
    p = a["prompt"].astype(np.float32); gt = a["gt"].astype(np.float32)
    ok = a["valid"] & a["gt_valid"] & (p > 0) & (gt > 0)
    bad = ok & (np.abs(p - gt) / np.where(gt > 0, gt, 1) > 0.05)
    clean = ok & ~bad; sc = bad & a["focus"]
    f = lambda m: float(flag[m].mean()) if m.any() else None
    return dict(recall_scope=f(sc), recall_all=f(bad), false_flag=f(clean))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", nargs="+", required=True); ap.add_argument("--caches", nargs="+", default=[])
    ap.add_argument("--output", default="docs/trust_mask_diagnostics")
    a = ap.parse_args()
    items, _ = load_items(a.data)
    items = [e for e in items if e["variant"] == "real" and
             (e["split"] == "val" or (e["split"] == "train" and scene_inner_holdout(e["dataset"], e["scene"])))]
    named = [kv.split("=", 1) for kv in a.caches]
    caches = {}
    for name, pattern in named:
        for ds, tag in TAGS.items():
            try:
                caches[(name, ds)] = TrustCache(pattern.replace("{tag}", tag))
            except FileNotFoundError:
                pass
    acc = {}
    for e in items:
        arr = np.load(e["file"]); arr = {k: arr[k] for k in arr.files}
        if "gt" not in arr:
            raise ValueError("needs v1 trust data")
        pop = "val" if e["split"] == "val" else "train holdout"
        p = arr["prompt"].astype(np.float32); dg = arr["dg"].astype(np.float32)
        with np.errstate(divide="ignore", invalid="ignore"):
            gate = arr["valid"] & ~(np.abs(p - dg) / dg <= 0.05)
        flags = {"Gate": gate}
        key = f"{e['sensor']}__{e['scene']}__{e['frame']}"
        for (name, ds), c in caches.items():
            if ds == e["dataset"] and key in c.index:
                t = np.load(c.root / c.index[key]["path"])["trust"].astype(np.float32)
                flags[name] = arr["valid"] & (t < c.threshold)
        for name, fl in flags.items():
            r = masks_for(arr, fl)
            d = acc.setdefault((e["dataset"], pop, name), {k: [] for k in r})
            for k, v in r.items():
                if v is not None:
                    d[k].append(v)
    lines = ["# Low-trust mask diagnostics (192x256 grid, out-of-fit populations)", "",
             "Generated by `python -m scripts.trust_mask_diagnostics`. Recall = flagged share of contaminated prompt pixels "
             "(scope: NYU mirror / HAMMER object; all: whole image). False flags = flagged share of clean prompt pixels. "
             "Image means. Thresholds (and v1 post-processing) are those chosen on the train holdout.", ""]
    payload = {}
    for ds in TAGS:
        for pop in ("val", "train holdout"):
            rows = [(n, v) for (d, p, n), v in acc.items() if d == ds and p == pop]
            if not rows:
                continue
            lines += [f"## {ds}, {pop}", "", "| Mask | recall (scope) | recall (all) | false flags | images |", "|---|---:|---:|---:|---:|"]
            for n, v in rows:
                m = {k: (float(np.mean(x)) if x else None) for k, x in v.items()}
                payload[f"{ds}/{pop}/{n}"] = dict(m, images=len(v["false_flag"]))
                fm = lambda x: "NA" if x is None else f"{x:.3f}"
                lines.append(f"| {n} | {fm(m['recall_scope'])} | {fm(m['recall_all'])} | {fm(m['false_flag'])} | {len(v['false_flag'])} |")
            lines.append("")
    (ROOT / f"{a.output}.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / f"{a.output}.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
