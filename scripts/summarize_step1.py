"""Step-1 table (plan revision v2), generated only from per-image machine results.

Main scope follows revision R2: NYU metrics on precise Mirror3D mirror pixels.
The full-image 'clean' column measures deviation from the inpainted sensor
reference, not GT accuracy; NYU 'hole' is not reported.
"""
import json
import numpy as np
from tp.eval.aggregate import aggregate
from tp.provenance import ROOT, write_json, sha256

RUNS = {
    "raw_prompt": "mirror3d_raw_prompt_smoke_v2",
    "UniDepthV2-S (no prompt)": "mirror3d_unidepth_smoke_v1",
    "RobustAlign global": "mirror3d_robust_global_smoke_v1",
    "RobustAlign local v1": "mirror3d_robust_local_smoke_v2",
    "RobustAlign local v2": "mirror3d_robust_local_v2_smoke_v2",
    "Gate (global)": "mirror3d_gate_global_smoke_v2",
    "Gate (local v2)": "mirror3d_gate_local_v2_smoke_v2",
}
fmt = lambda v: "NA" if v is None else f"{v:.4f}"


def scene_mean_trust(rows):
    by_scene = {}
    for r in rows:
        a = r["trust_quality"].get("auroc")
        by_scene.setdefault(r["scene"], []).append(a)
    if any(a is None for v in by_scene.values() for a in v):
        return None
    return float(np.mean([np.mean(v) for v in by_scene.values()]))


def main():
    out, mirror_lines, full_lines = {}, [], []
    for name, run in RUNS.items():
        base = ROOT / "results" / run
        mirror_rows = json.loads((base / "per_image_mirror_only.json").read_text())
        rows = json.loads((base / "per_image.json").read_text())
        mm = aggregate(mirror_rows)["datasets"]["mirror3d_nyu"]["metrics"]
        fm = aggregate(rows)["datasets"]["mirror3d_nyu"]["metrics"]
        r = mm["regions"]
        mirror_lines.append("| " + " | ".join([name, fmt(r["C"]["absrel"]), fmt(r["C"]["delta_1_05"]),
                            fmt(r["band"]["absrel"]), fmt(mm["IR"]["value"]), fmt(mm["DOR"]["value"]),
                            str(r["all"]["invalid_count"])]) + " |")
        f = fm["regions"]
        auroc = scene_mean_trust(rows)
        full_lines.append("| " + " | ".join([name, fmt(f["C"]["absrel"]), fmt(f["clean"]["absrel"]),
                          fmt(fm["IR"]["value"]), fmt(fm["DOR"]["value"]), fmt(auroc),
                          str(f["all"]["invalid_count"])]) + " |")
        out[name] = dict(run=run, per_image_sha256=sha256(base / "per_image.json"),
                         per_image_mirror_only_sha256=sha256(base / "per_image_mirror_only.json"),
                         mirror_only=mm, full_image=fm, gate_auroc_scene_mean=auroc)
    lines = [
        "# Step 1 results: NYU 5-frame training diagnostic (plan revision v2)", "",
        "Generated by `python -m scripts.summarize_step1` from per-image JSON. Same 5 training frames/scenes as the smoke run; "
        "no test data, no scale alignment, image→scene→dataset equal weighting. **Engineering diagnostic, not a formal result.**", "",
        "## Main scope (R2): precise Mirror3D mirror pixels", "",
        "| Method | C AbsRel | C δ<1.05 | band AbsRel | IR | DOR | Invalid px |",
        "|---|---:|---:|---:|---:|---:|---:|", *mirror_lines, "",
        "## Full image (R2 semantics)", "",
        "`clean` = deviation from the inpainted sensor reference (not GT accuracy). Gate AUROC = binary agreement map vs clean_all label, scene mean.", "",
        "| Method | C AbsRel | clean (vs inpainted) | IR | DOR | Gate AUROC | Invalid px |",
        "|---|---:|---:|---:|---:|---:|---:|", *full_lines, "",
        "Paired scene bootstrap (reference = RobustAlign global): `results/mirror3d_paired_comparison_step1_v1/paired_bootstrap.json`.", "",
    ]
    (ROOT / "docs/step1_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/step1_results.json", dict(stage="real_train_engineering_diagnostic", methods=out))


if __name__ == "__main__":
    main()
