"""Revision R14 experiments: (b) fill-selection rules with GT contamination masks and
(a) the DEPTHOR++-style detector as a deployable trust source. Development
diagnostics on train/val only.

  python -m scripts.summarize_selection   ->  docs/selection_results.md / .json

Gap closure = (v1 - rule) / (v1 - oracle_best) on C AbsRel of the main scope; NA when
oracle_best was not run for that split. Oracle match / regret come from the per-region
GT errors that run_eval stores for analysis only (fill_summary.selection).
"""
import json

import numpy as np

from tp.eval.aggregate import aggregate
from tp.provenance import ROOT, write_json

DATA = {"mirror3d_nyu": ("mirror3d_dev", "mirror_only", "NYU mirrors"),
        "hammer": ("hammer_dev", "objects_only", "HAMMER objects")}
RULES = ["v1", "aic", "gric", "holdout_sector", "holdout_radial", "oracle_best"]
DETECT = [("RobustAlign global", "robust_global"), ("PromptDA-L", "promptda_vitl_raw"),
          ("Gate + v1", "trustfill_gate_global_v1"), ("Detector + k0", "trustfill_depthor_k0"),
          ("Detector + v1", "trustfill_depthor_v1"), ("Detector + sector hold-out", "trustfill_depthor_holdout_sector"),
          ("PromptDA-L + detector mask", "promptda_vitl_detector_prior"),
          ("GT mask + v1 [oracle]", "trustfill_oracle_c_v1"),
          ("PromptDA-L + GT mask [oracle]", "promptda_vitl_oracle_prior")]
fmt = lambda v, d=4: "NA" if v is None or (isinstance(v, float) and not np.isfinite(v)) else f"{v:.{d}f}"


def load(prefix, key, split, scope, ds):
    base = ROOT / "results" / f"{prefix}_{key}_{split}_v1"
    if not (base / "receipt.json").is_file():
        return None
    rows = json.loads((base / "per_image.json").read_text())
    sc = json.loads((base / f"per_image_{scope}.json").read_text())
    m = aggregate(sc)["datasets"][ds]["metrics"]; f = aggregate(rows)["datasets"][ds]["metrics"]
    sel = [r["fill_summary"].get("selection") for r in rows if r.get("fill_summary")]
    sel = [x for x in sel if x]
    det = [r["fill_summary"].get("detector") for r in rows if r.get("fill_summary")]
    det = [x for x in det if x]
    au = [r["trust_quality"].get("auroc") for r in rows if isinstance(r.get("trust_quality"), dict)]
    au = [a for a in au if a is not None]
    return dict(run=base.name, images=len(rows), c=m["regions"]["C"]["absrel"], ir=m["IR"]["value"], dor=m["DOR"]["value"],
                c_full=f["regions"]["C"]["absrel"], clean_full=f["regions"]["clean"]["absrel"],
                oracle_match=float(np.mean([x["oracle_match_area_fraction"] for x in sel])) if sel else None,
                regret=float(np.mean([x["area_weighted_regret"] for x in sel])) if sel else None,
                auroc_image_mean=float(np.mean(au)) if au else None,
                detector=dict(gamma_mean=float(np.mean([x["gamma"] for x in det if x.get("gamma") is not None])),
                              modes={k: sum(1 for x in det if x.get("threshold_mode") == k)
                                     for k in ("gamma_gt_hi_no_anomaly", "blend", "otsu")},
                              anomaly_fraction=float(np.mean([x["anomaly_pixels"] / max(1, x["valid_pixels"]) for x in det])))
                if det else None)


def main():
    lines = ["# R14 experiments: fill selection rules and DEPTHOR++-style detector", "",
             "Generated by `python -m scripts.summarize_selection`. Development diagnostics on train/val only; test never "
             "read; no scale alignment. C AbsRel is on the main scope (NYU mirror pixels / HAMMER object pixels).", ""]
    payload = {}
    for ds, (prefix, scope, label) in DATA.items():
        for split in ("val", "train"):
            res = {r: load(prefix, f"trustfill_oracle_c_{r}", split, scope, ds) for r in RULES}
            if not any(res.values()):
                continue
            v1 = res["v1"]["c"] if res["v1"] else None; ob = res["oracle_best"]["c"] if res["oracle_best"] else None
            lines += [f"## {label}, {split}: selection rules (GT contamination mask)", "",
                      "| Rule | C AbsRel | gap closed | oracle-match area | regret | IR | DOR |", "|---|---:|---:|---:|---:|---:|---:|"]
            for r in RULES:
                x = res[r]
                if not x:
                    continue
                gap = (v1 - x["c"]) / (v1 - ob) if None not in (v1, ob) and x["c"] is not None and v1 != ob else None
                x["gap_closed"] = gap
                lines.append(f"| {r} | {fmt(x['c'])} | {fmt(gap, 2)} | {fmt(x['oracle_match'], 2)} | {fmt(x['regret'])} | "
                             f"{fmt(x['ir'])} | {fmt(x['dor'])} |")
            lines.append("")
            det = {k: load(prefix, k, split, scope, ds) for _, k in DETECT}
            lines += [f"## {label}, {split}: detector as trust source", "",
                      "| Method | C AbsRel (scope) | C AbsRel (full) | clean (full) | IR | DOR | trust AUROC |",
                      "|---|---:|---:|---:|---:|---:|---:|"]
            for name, k in DETECT:
                x = det[k]
                if x:
                    lines.append(f"| {name} | {fmt(x['c'])} | {fmt(x['c_full'])} | {fmt(x['clean_full'])} | {fmt(x['ir'])} | "
                                 f"{fmt(x['dor'])} | {fmt(x['auroc_image_mean'], 3)} |")
            d = (det.get("trustfill_depthor_v1") or {}).get("detector")
            if d:
                lines += ["", f"Detector: mean Spearman γ {d['gamma_mean']:.3f}; threshold modes {d['modes']}; "
                              f"mean flagged fraction of valid prompt {d['anomaly_fraction']:.3f}."]
            lines.append("")
            payload[f"{ds}/{split}"] = dict(selection=res, detector=det)
    (ROOT / "docs/selection_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/selection_results.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
