"""Formal test (docs/plan_test.md, secondary): does the frozen conformal threshold keep its guarantee on the test split?

  python -m scripts.conformal_test_check

Loss per test image = share of far-contaminated main-scope prompt pixels (P > (1 + danger_tau) GT, danger_tau from
the frozen threshold file) that T v1 leaves unflagged at the frozen lambda (alpha 0.1). Reported: mean loss (the
quantity the guarantee bounds by alpha), the share of images whose loss exceeds alpha, and the false-flag rate on
clean pixels. Descriptive; nothing is re-tuned. 192x256 grid, as in the calibration.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime

import numpy as np

from scripts.train_trust import load_items
from tp.formal import guard
from tp.provenance import ROOT, sha256, start_run, write_json
from tp.trust.cache import TrustCache
from tp.trust.conformal import image_losses

CRC = "results/trust_t_v1_crc_d20.json"
ALPHA = "0.1"
SETS = {"mirror3d_nyu": ("cache/trust_data_v1_nyu_test", "cache/trust_t_v1_real_sim_nofeat_nyu_test_v1"),
        "hammer": ("cache/trust_data_v1_hammer_test", "cache/trust_t_v1_real_sim_nofeat_hammer_test_v1")}


def main():
    formal = guard()
    crc = json.loads((ROOT / CRC).read_text(encoding="utf-8"))
    danger_tau = float(crc["danger_tau"])
    out = ROOT / "results" / f"conformal_test_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    receipt = start_run(out, dict(crc=CRC, alpha=ALPHA, danger_tau=danger_tau, sets=SETS, formal_test=formal),
                        [sys.executable, "-m", "scripts.conformal_test_check", *sys.argv[1:]], 0)
    try:
        res, lines = {}, ["# Conformal guarantee on the test split (formal test, secondary)", "",
                          f"Generated by `python -m scripts.conformal_test_check` ({out.name}). Frozen lambda from `{CRC}` "
                          f"at alpha {ALPHA}; danger = P > {1 + danger_tau:.2f} GT; loss = unflagged share of far-contaminated "
                          "main-scope prompt pixels per image; 192x256 grid.", "",
                          "| dataset | lambda | test images (with far pixels) | mean loss | mean loss <= alpha | images with loss > alpha | false flags on clean pixels |",
                          "|---|---:|---:|---:|---|---:|---:|"]
        for ds, (data, cache) in SETS.items():
            lam = float(crc["datasets"][ds]["alphas"][ALPHA]["lambda_hat"])
            tc = TrustCache(ROOT / cache)
            items = [e for e in load_items([data], allow_test=True)[0] if e["variant"] == "real" and e["split"] == "test"]
            L, F, N = [], [], []
            for e in items:
                a = np.load(e["file"]); a = {k: a[k] for k in a.files}
                t = np.load(tc.root / tc.index[f"{e['sensor']}__{e['scene']}__{e['frame']}"]["path"])["trust"].astype(np.float32)
                l, f, n = image_losses(t, a, grid=np.array([lam]), tau=danger_tau)
                L.append(float(l[0])); F.append(float(f[0])); N.append(n)
            L, F, N = np.array(L), np.array(F), np.array(N)
            res[ds] = dict(lambda_hat=lam, images=len(items), images_with_far=int((N > 0).sum()), mean_loss=float(L.mean()),
                           holds=bool(L.mean() <= float(ALPHA)), share_images_loss_gt_alpha=float((L > float(ALPHA)).mean()),
                           false_flags=float(F.mean()), trust_cache_receipt_sha256=sha256(tc.root / "receipt.json"))
            r = res[ds]
            lines.append(f"| {ds} | {lam:.3f} | {r['images']} ({r['images_with_far']}) | {r['mean_loss']:.3f} | "
                         f"{'yes' if r['holds'] else 'NO'} | {r['share_images_loss_gt_alpha']:.2f} | {r['false_flags']:.3f} |")
        lines.append("")
        write_json(out / "conformal_test.json", res)
        (ROOT / "docs" / "conformal_test.md").write_text("\n".join(lines), encoding="utf-8")
        receipt.update(stage="complete", result_sha256=sha256(out / "conformal_test.json"))
        print("\n".join(lines))
    except BaseException as e:
        receipt.update(stage="failed", error=repr(e))
        raise
    finally:
        write_json(out / "receipt.json", receipt)


if __name__ == "__main__":
    main()
