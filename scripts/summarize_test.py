"""Formal test tables (docs/plan_test.md): raw vs + T v1 mask vs GT mask per model -> docs/test_results.md / .json.

  python -m scripts.summarize_test

Same rows and metrics as scripts.summarize_baselines (main-scope C AbsRel, whole-image C, clean, IR, DOR, images
with invalid predictions), on the test runs results/<prefix>_<run>_test_v1. The statistical test is the
pre-registered Holm family (configs/baselines/holm_family_test_v1.yaml, docs/holm_test_v1.md).
"""
import yaml

from scripts.summarize_baselines import fmt, row
from tp.provenance import ROOT, write_json

PROMPTDA = [("raw", "promptda_vitl_raw"), ("T v1 mask, D_g fill", "promptda_vitl_trust_v1_crc10_prior"),
            ("GT mask, D_g fill [oracle]", "promptda_vitl_oracle_prior")]
VAR = [("raw", "raw"), ("T v1 mask", "tmask"), ("GT mask [oracle]", "oracle_mask")]


def main():
    spec = yaml.safe_load((ROOT / "configs/baselines/holm_family_test_v1.yaml").read_text(encoding="utf-8"))
    lines = ["# Formal test: depth-completion models with and without T v1", "",
             "Generated by `python -m scripts.summarize_test`. Test split, read once after the method v1 freeze "
             "(docs/freeze_method_v1.md, docs/plan_test.md). NYU: registered Z (formal_test_registered_z); HAMMER: "
             "formal_main_result. Main-scope C AbsRel (NYU mirror / HAMMER object pixels), `C full` whole image, `clean` "
             "main-scope pixels whose prompt was correct, IR / DOR. Statistical test: docs/holm_test_v1.md.", ""]
    payload = {}
    head = ["| Model | Prompt | C AbsRel | C full | clean | IR | DOR | invalid imgs |", "|---|---|---:|---:|---:|---:|---:|---:|"]
    for ds, dd in spec["datasets"].items():
        body, n = [], None
        for mk, m in spec["models"].items():
            runs = PROMPTDA if mk == "promptda_l" else [(lab, f"bl_{mk}_{v}") for lab, v in VAR]
            for lab, run in runs:
                x = row(ds, dd["prefix"], dd["scope"], run, "test", False)
                payload.setdefault(ds, {}).setdefault(mk, {})[lab] = x
                if x is None:
                    body.append(f"| {m['label']} | {lab} | missing | | | | | |")
                    continue
                n = n or (x["images"], x["scenes"])
                body.append(f"| {m['label']} | {lab} | {fmt(x['c'])} | {fmt(x['c_full'])} | {fmt(x['clean'])} | "
                            f"{fmt(x['ir'])} | {fmt(x['dor'])} | {x['images_with_invalid']} |")
        lines += [f"## {ds}, test" + ("" if n is None else f": {n[0]} images / {n[1]} scenes"), "", *head, *body, ""]
    write_json(ROOT / "docs" / "test_results.json", payload)
    (ROOT / "docs" / "test_results.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
