"""NYU development-set tables (plan revision v2, step 1c), from per-image JSON only.

Main scope (R2): precise Mirror3D mirror pixels. Full-image `clean` = deviation from
the inpainted sensor reference, not GT accuracy. Train and val reported separately;
val is the selection split. Test is never read.
"""
import json
import numpy as np
from tp.eval.aggregate import aggregate
from tp.provenance import ROOT, sha256, write_json

METHODS = [("raw_prompt", "raw_prompt"), ("UniDepthV2-S (no prompt)", "unidepth_v2_s"),
           ("RobustAlign global", "robust_global"), ("RobustAlign local v2", "robust_local_v2"),
           ("Gate (global)", "gate_global"), ("Gate (local v2)", "gate_local_v2")]
fmt = lambda v: "NA" if v is None else f"{v:.4f}"


def scene_auroc(rows):
    scenes = {}
    for r in rows:
        scenes.setdefault(r["scene"], []).append(r["trust_quality"].get("auroc"))
    vals = [np.mean(v) for v in scenes.values() if all(a is not None for a in v)]
    return float(np.mean(vals)) if vals and len(vals) == len(scenes) else None


DATASETS = {"mirror3d_nyu": dict(prefix="mirror3d_dev", scope="mirror_only", scope_label="Mirror pixels (main scope)",
                                 out="dev_results", paired="mirror3d_dev_paired_val_v2"),
            "hammer": dict(prefix="hammer_dev", scope="objects_only",
                           scope_label="Object pixels, GT vs naked GT (main scope)", out="hammer_dev_results",
                           paired="hammer_dev_paired_val_v1")}
CFG = DATASETS["mirror3d_nyu"]


def table(split):
    mirror, full, out = [], [], {}
    for name, key in METHODS:
        base = ROOT / "results" / f"{CFG['prefix']}_{key}_{split}_v1"
        receipt = json.loads((base / "receipt.json").read_text())
        mr = json.loads((base / f"per_image_{CFG['scope']}.json").read_text())
        fr = json.loads((base / "per_image.json").read_text())
        ds = CFG["dataset"]
        mm = aggregate(mr)["datasets"][ds]; fm = aggregate(fr)["datasets"][ds]
        m, f = mm["metrics"], fm["metrics"]
        mirror.append("| " + " | ".join([name, fmt(m["regions"]["C"]["absrel"]), fmt(m["regions"]["C"]["delta_1_05"]),
                      fmt(m["regions"]["Cfar"]["absrel"]), fmt(m["regions"]["band"]["absrel"]),
                      fmt(m["IR"]["value"]), fmt(m["DOR"]["value"])]) + " |")
        full.append("| " + " | ".join([name, fmt(f["regions"]["C"]["absrel"]), fmt(f["regions"]["clean"]["absrel"]),
                    fmt(f["IR"]["value"]), fmt(f["DOR"]["value"]), fmt(scene_auroc(fr)),
                    str(f["regions"]["all"]["invalid_count"])]) + " |")
        out[name] = dict(run=base.name, stage=receipt["stage"], git_commit=receipt.get("git_commit"),
                         per_image_sha256=sha256(base / "per_image.json"), images=fm["image_count"],
                         scenes=fm["scene_count"], mirror_only=m, full_image=f, gate_auroc_scene_mean=scene_auroc(fr))
    n = out[METHODS[0][0]]
    head = [f"## {split}: {n['images']} images / {n['scenes']} scenes", "",
            CFG["scope_label"] + ":", "",
            "| Method | C AbsRel | C δ<1.05 | Cfar AbsRel | band AbsRel | IR | DOR |",
            "|---|---:|---:|---:|---:|---:|---:|", *mirror, "",
            "Full image (`clean` = deviation from inpainted sensor reference):", "",
            "| Method | C AbsRel | clean | IR | DOR | Gate AUROC | Invalid px |",
            "|---|---:|---:|---:|---:|---:|---:|", *full, ""]
    return head, out


def main():
    import argparse
    global CFG
    ap = argparse.ArgumentParser(); ap.add_argument("--dataset", default="mirror3d_nyu", choices=sorted(DATASETS))
    a = ap.parse_args(); CFG = dict(DATASETS[a.dataset], dataset=a.dataset)
    if a.dataset == "hammer":
        return main_hammer()
    lines = ["# NYU development set: baseline diagnostics (plan revision v2, step 1c)", "",
             "Generated by `python -m scripts.summarize_dev`. No scale alignment; image→scene→dataset equal weights; "
             "test split never read. **Development diagnostics, not formal results.** "
             "RGB-Z gap on these 95 frames ≤ 0.473% (`results/nyu_rgbz_bound_dev_v1b`).", ""]
    payload = {}
    for split in ("val", "train"):
        body, out = table(split); lines += body; payload[split] = out
    lines += ["Paired scene bootstrap on val (reference = RobustAlign global): "
              "`results/mirror3d_dev_paired_val_v2/paired_bootstrap.json` (empty-region scenes excluded and listed).", ""]
    (ROOT / "docs/dev_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/dev_results.json", dict(stage="development_diagnostic", splits=payload))


def main_hammer():
    lines = ["# HAMMER development subset: baseline diagnostics", "",
             "Generated by `python -m scripts.summarize_dev --dataset hammer`. Train stride 20 / val stride 5 frames, "
             "3 sensors per frame (D435, L515, Helios ToF) pooled with equal image weights; no scale alignment; test scenes "
             "12-14 never read. **Development diagnostics, not formal results.** Main scope: object pixels "
             "(rendered GT differs from the naked GT by > 1 mm). Full-image regions include sensor errors on the "
             "background (D435 +2-4% bias, Helios on dark surfaces; docs/hammer_audit.md).", ""]
    payload = {}
    for split in ("val", "train"):
        body, out = table(split); lines += body; payload[split] = out
    (ROOT / f"docs/{CFG['out']}.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / f"docs/{CFG['out']}.json", dict(stage="development_diagnostic", splits=payload))


if __name__ == "__main__":
    main()
