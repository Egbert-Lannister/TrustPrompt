"""Run a pre-registered comparison family with Holm adjustment -> results/holm_<family>/ and docs/holm_<family>.md.

  python -m scripts.holm_family [--spec configs/baselines/holm_family_v1.yaml]

Each comparison reads per_image_<scope>.json of a reference and a candidate evaluation run
(results/<prefix>_<run>_<split>_v1). Population val = split val; train_holdout = split train restricted to the
holdout scenes. Missing runs and invalid values stay in the family with p = 1 (tp.eval.family). Development
diagnostics only; the test split is never read.
"""
import argparse
from datetime import datetime
import json
import sys
from pathlib import Path

import yaml

from tp.eval.family import compare, holm_family
from tp.provenance import ROOT, sha256, start_run, write_json

# all_dev = every development scene (train + val splits); used with cross-fitted T, where each scene's trust map
# comes from a fold that never saw that scene.
POP_SPLIT = {"val": ["val"], "train_holdout": ["train"], "all_dev": ["train", "val"]}


def load_rows(prefix, run, splits, scope, dataset, population):
    rows, hashes, names = [], [], []
    for split in splits:
        d = ROOT / "results" / f"{prefix}_{run}_{split}_v1"
        f = d / f"per_image_{scope}.json"
        rec = d / "receipt.json"
        if not f.is_file() or not rec.is_file():
            return None, str(d)
        stage = json.loads(rec.read_text(encoding="utf-8")).get("stage")
        if stage not in ("small_scale_validation_passed", "completed_with_invalid_predictions"):
            return None, f"{d} (stage {stage})"
        part = json.loads(f.read_text(encoding="utf-8"))
        if population == "train_holdout":
            from tp.trust.data import scene_inner_holdout
            part = [r for r in part if scene_inner_holdout(dataset, r["scene"])]
        rows += part; hashes.append(sha256(f)); names.append(d.name)
    return dict(rows=rows, sha256=hashes if len(hashes) > 1 else hashes[0], run="+".join(names)), "+".join(names)


def fmt(v, d=4):
    return "NA" if v is None else f"{v:.{d}f}"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--spec", default="configs/baselines/holm_family_v1.yaml")
    a = ap.parse_args()
    spec_path = ROOT / a.spec
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    out = ROOT / "results" / f"holm_{spec['family']}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    receipt = start_run(out, dict(spec, spec_sha256=sha256(spec_path)),
                        [sys.executable, "-m", "scripts.holm_family", *sys.argv[1:]], int(spec["seed"]))
    try:
        payload = {}
        lines = [f"# Comparison family `{spec['family']}` (Holm, alpha = {spec['alpha']})", "",
                 "Generated by `python -m scripts.holm_family` from the pre-registered spec "
                 f"`{a.spec}`. Difference = candidate - reference of the main-scope {spec['region']} {spec['metric']} "
                 "(negative = candidate better). Unit `scene` = paired scene bootstrap; `frame_block` = circular "
                 f"block bootstrap of frames (L = {spec['block_length']}) inside a single scene, i.e. inference about "
                 "frames of that scene only. NA comparisons stay in the family with p = 1. Development diagnostics; "
                 "test never read.", ""]
        for fam, fdef in spec["families"].items():
            pop = fdef["population"]; split = POP_SPLIT[pop]
            results = {}
            for mk, m in spec["models"].items():
                for ds, dd in spec["datasets"].items():
                    cid = f"{mk}/{ds}/{pop}"
                    ref, rpath = load_rows(dd["prefix"], m["reference"], split, dd["scope"], ds, pop)
                    cand, cpath = load_rows(dd["prefix"], m["candidate"], split, dd["scope"], ds, pop)
                    if ref is None or cand is None:
                        results[cid] = dict(status="NA_missing_run", p_value=None, missing=[p for x, p in ((ref, rpath), (cand, cpath)) if x is None],
                                            model=m["label"], dataset=ds, population=pop)
                        continue
                    try:
                        r = compare(ref["rows"], cand["rows"], dataset=ds, region=spec["region"], metric=spec["metric"],
                                    n_resamples=int(spec["n_resamples"]), seed=int(spec["seed"]), block_length=int(spec["block_length"]))
                    except ValueError as e:
                        r = dict(status=f"NA_error: {e}", p_value=None)
                    try:      # over-masking check (decisions sec. 18): clean region, descriptive, not in the family
                        cl = compare(ref["rows"], cand["rows"], dataset=ds, region="clean", metric=spec["metric"],
                                     n_resamples=int(spec["n_resamples"]), seed=int(spec["seed"]), block_length=int(spec["block_length"]))
                        rel = (cl["mean_difference"] / cl["reference_mean"]) if cl.get("mean_difference") is not None and cl.get("reference_mean") else None
                        r["clean_check"] = dict(reference_mean=cl.get("reference_mean"), candidate_mean=cl.get("candidate_mean"),
                                                mean_difference=cl.get("mean_difference"), ci_low=cl.get("ci_low"), ci_high=cl.get("ci_high"),
                                                relative_change=rel, unit=cl.get("unit"), status=cl.get("status"),
                                                clearly_worse=bool(cl.get("ci_low") is not None and cl["ci_low"] > 0 and rel is not None and rel > 0.2))
                    except ValueError as e:
                        r["clean_check"] = dict(status=f"NA_error: {e}", clearly_worse=None)
                    r.update(model=m["label"], dataset=ds, population=pop, reference_run=ref["run"], candidate_run=cand["run"],
                             reference_sha256=ref["sha256"], candidate_sha256=cand["sha256"])
                    results[cid] = r
            holm_family(results, alpha=float(spec["alpha"]))
            payload[fam] = results
            lines += [f"## {fam} family: population {pop} ({len(results)} comparisons)", "",
                      "| Model | Dataset | reference | candidate | difference [95% CI] | unit | p | p (Holm) | reject |",
                      "|---|---|---:|---:|---|---|---:|---:|---|"]
            for cid, r in results.items():
                ci = (f"{fmt(r.get('mean_difference'))} [{fmt(r.get('ci_low'))}, {fmt(r.get('ci_high'))}]"
                      if r.get("mean_difference") is not None else r.get("status", "NA"))
                lines.append(f"| {r['model']} | {r['dataset']} | {fmt(r.get('reference_mean'))} | {fmt(r.get('candidate_mean'))} | "
                             f"{ci} | {r.get('unit', '-')} | {fmt(r.get('p_value'), 4)} | {fmt(r.get('p_holm'), 4)} | "
                             f"{'yes' if r.get('reject_at_alpha') else 'no'} |")
            lines += ["", f"Over-masking check, population {pop} (clean main-scope pixels; descriptive, decisions sec. 18: "
                      "clearly worse = CI lower bound > 0 and mean rise > 20%):", "",
                      "| Model | Dataset | clean ref | clean cand | difference [95% CI] | relative | clearly worse |",
                      "|---|---|---:|---:|---|---:|---|"]
            for cid, r in results.items():
                c = r.get("clean_check") or {}
                ci = (f"{fmt(c.get('mean_difference'))} [{fmt(c.get('ci_low'))}, {fmt(c.get('ci_high'))}]"
                      if c.get("mean_difference") is not None else c.get("status", "NA"))
                rel = "NA" if c.get("relative_change") is None else f"{100 * c['relative_change']:+.0f}%"
                lines.append(f"| {r['model']} | {r['dataset']} | {fmt(c.get('reference_mean'))} | {fmt(c.get('candidate_mean'))} | "
                             f"{ci} | {rel} | {c.get('clearly_worse')} |")
            lines.append("")
        write_json(out / "family_results.json", payload)
        (ROOT / "docs" / f"holm_{spec['family']}.md").write_text("\n".join(lines), encoding="utf-8")
        receipt.update(stage="descriptive_comparison_complete", formal_experiment_complete=False,
                       results_sha256=sha256(out / "family_results.json"))
    except BaseException as e:
        receipt.update(stage="failed", error=repr(e)); raise
    finally:
        write_json(out / "receipt.json", receipt)


if __name__ == "__main__":
    main()
