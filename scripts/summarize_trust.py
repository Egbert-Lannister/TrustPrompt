"""T v0 development tables -> docs/trust_v0_results.md / .json.

T is fitted on train-split scenes, so results are reported on three populations:
  val                 out of sample (never read by training or selection)
  train, holdout      train-split scenes held out for T model selection (out of fit, used for selection)
  train, all          in sample for T (fitted scenes included); shown only for the baselines' context
Scope = NYU mirror pixels / HAMMER object pixels; image -> scene -> dataset equal weights.
"""
import json

import numpy as np

from tp.eval.aggregate import aggregate
from tp.provenance import ROOT, write_json
from tp.trust.data import scene_inner_holdout

REGIMES = ["real", "sim", "real_sim", "real_sim_nofeat"]
METHODS = [("RobustAlign global", "robust_global"), ("PromptDA-L", "promptda_vitl_raw"),
           ("Gate + fill v1", "trustfill_gate_global_v1"), ("Detector (gate off) + fill v1", "trustfill_depthor_nogate_v1"),
           *[(f"T v0 [{r}] + fill v1", f"trustfill_t_v0_{r}_v1") for r in REGIMES],
           ("PromptDA-L + Gate mask", "promptda_vitl_gate_prior"),
           ("PromptDA-L + detector mask (gate off)", "promptda_vitl_detector_nogate_prior"),
           ("PromptDA-L + T v0 mask [selected regime]", "promptda_vitl_trust_prior"),
           ("GT mask + fill v1 [oracle]", "trustfill_oracle_c_v1"),
           ("PromptDA-L + GT mask [oracle]", "promptda_vitl_oracle_prior")]
DATA = {"mirror3d_nyu": ("mirror3d_dev", "mirror_only", "NYU mirrors"), "hammer": ("hammer_dev", "objects_only", "HAMMER objects")}
fmt = lambda v, d=4: "NA" if v is None else f"{v:.{d}f}"


def scene_auroc(rows):
    by = {}
    for r in rows:
        a = (r.get("trust_quality") or {}).get("auroc")
        by.setdefault(r["scene"], []).append(a)
    vals = [np.mean(v) for v in by.values() if v and all(a is not None for a in v)]
    return float(np.mean(vals)) if vals and len(vals) == len(by) else None


def block(ds, prefix, scope, split, holdout_only):
    lines, out = [], {}
    for name, key in METHODS:
        base = ROOT / "results" / f"{prefix}_{key}_{split}_v1"
        if not (base / "receipt.json").is_file():
            continue
        sc = json.loads((base / f"per_image_{scope}.json").read_text())
        full = json.loads((base / "per_image.json").read_text())
        if holdout_only:
            sc = [r for r in sc if scene_inner_holdout(ds, r["scene"])]
            full = [r for r in full if scene_inner_holdout(ds, r["scene"])]
        if not sc:
            continue
        m = aggregate(sc)["datasets"][ds]["metrics"]; agg = aggregate(full)["datasets"][ds]
        out[key] = dict(run=base.name, images=agg["image_count"], scenes=agg["scene_count"], c=m["regions"]["C"]["absrel"],
                        ir=m["IR"]["value"], dor=m["DOR"]["value"], c_full=agg["metrics"]["regions"]["C"]["absrel"],
                        trust_auroc=scene_auroc(full))
        x = out[key]
        lines.append(f"| {name} | {fmt(x['c'])} | {fmt(x['c_full'])} | {fmt(x['ir'])} | {fmt(x['dor'])} | {fmt(x['trust_auroc'], 3)} |")
    return lines, out


def main():
    lines = ["# T v0: development results", "",
             "Generated by `python -m scripts.summarize_trust`. Development diagnostics; test never read; no scale alignment. "
             "C AbsRel on the main scope (NYU mirror / HAMMER object pixels); `C full` = whole image. "
             "Trust AUROC: clean prompt pixels as positives, scene mean. **val and train-holdout are out of fit for T; "
             "train-all is in sample for T.**", ""]
    payload = {}
    for r in REGIMES:
        p = ROOT / "results" / f"trust_t_v0_{r}"
        if (p / "receipt.json").is_file():
            rec = json.loads((p / "receipt.json").read_text())
            payload.setdefault("models", {})[r] = {k: rec.get(k) for k in ("stage", "best", "pos_weight", "counts", "train_seconds", "parameters")}
    if payload.get("models"):
        lines += ["## Models (selection on train-split holdout scenes)", "",
                  "| Regime | stage | selection AUROC | threshold | F1 | params | train s |", "|---|---|---:|---:|---:|---:|---:|"]
        for r, m in payload["models"].items():
            b = m.get("best") or {}
            lines.append(f"| {r} | {m['stage']} | {fmt(b.get('selection_auroc'), 3)} | {b.get('threshold')} | "
                         f"{fmt(b.get('mean_f1'), 3)} | {m.get('parameters')} | {fmt(m.get('train_seconds'), 0)} |")
        lines.append("")
    head = ["| Method | C AbsRel | C full | IR | DOR | trust AUROC |", "|---|---:|---:|---:|---:|---:|"]
    for ds, (prefix, scope, label) in DATA.items():
        for split, hold, tag in (("val", False, "val (out of sample)"), ("train", True, "train holdout scenes (out of fit)"),
                                 ("train", False, "train all (in sample for T)")):
            body, out = block(ds, prefix, scope, split, hold)
            if body:
                n = next(iter(out.values()))
                lines += [f"## {label}, {tag}: {n['images']} images / {n['scenes']} scenes", "", *head, *body, ""]
                payload[f"{ds}/{tag}"] = out
    (ROOT / "docs/trust_v0_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/trust_v0_results.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
