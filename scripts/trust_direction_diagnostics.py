"""T v2 direction diagnostics on the 192x256 grid, out-of-fit populations (val, train-holdout scenes).

  python -m scripts.trust_direction_diagnostics --data cache/trust_data_v1_nyu cache/trust_data_v1_hammer \
      --caches v2_real_sim_nofeat=cache/trust_t_v2_real_sim_nofeat_{tag}_dev_v1 ...

Per image, over contaminated main-scope prompt pixels: share of 'measured too far' pixels predicted far
(far recall), share of 'measured too near' pixels predicted near (near recall), and overall sign accuracy;
also restricted to pixels the model flags (trust < its threshold). Image means. -> docs/trust_direction_diagnostics.md
"""
import argparse

import numpy as np

from scripts.train_trust import load_items
from scripts.trust_mask_diagnostics import TAGS
from tp.provenance import ROOT, write_json
from tp.trust.cache import TrustCache
from tp.trust.data import labels3_from_arrays, scene_inner_holdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", nargs="+", required=True); ap.add_argument("--caches", nargs="+", required=True)
    ap.add_argument("--output", default="docs/trust_direction_diagnostics")
    a = ap.parse_args()
    items = [e for e in load_items(a.data)[0] if e["variant"] == "real" and
             (e["split"] == "val" or (e["split"] == "train" and scene_inner_holdout(e["dataset"], e["scene"])))]
    caches = {}
    for kv in a.caches:
        name, pat = kv.split("=", 1)
        for ds, tag in TAGS.items():
            try:
                caches[(name, ds)] = TrustCache(pat.replace("{tag}", tag))
            except FileNotFoundError:
                pass
    acc = {}
    for e in items:
        z = np.load(e["file"]); arr = {k: z[k] for k in z.files}
        lab = labels3_from_arrays(arr); sc = arr["focus"]
        far_t, near_t = (lab == 1) & sc, (lab == 2) & sc
        key = f"{e['sensor']}__{e['scene']}__{e['frame']}"
        pop = "val" if e["split"] == "val" else "train holdout"
        for (name, ds), c in caches.items():
            if ds != e["dataset"] or key not in c.index:
                continue
            q = np.load(c.root / c.index[key]["path"])
            if "p_far" not in q.files:
                continue
            pf, pn, tr = (q[k].astype(np.float32) for k in ("p_far", "p_near", "trust"))
            pred_far = pf >= pn; flag = arr["valid"] & (tr < c.threshold)
            d = acc.setdefault((ds, pop, name), {k: [] for k in ("far_recall", "near_recall", "sign_acc",
                                                                 "far_recall_flagged", "sign_acc_flagged", "near_share")})
            con = far_t | near_t
            if far_t.any(): d["far_recall"].append(float(pred_far[far_t].mean()))
            if near_t.any(): d["near_recall"].append(float((~pred_far)[near_t].mean()))
            if con.any():
                d["sign_acc"].append(float(((pred_far & far_t) | (~pred_far & near_t))[con].mean()))
                d["near_share"].append(float(near_t[con].mean()))
            fc = con & flag
            if (far_t & flag).any(): d["far_recall_flagged"].append(float(pred_far[far_t & flag].mean()))
            if fc.any(): d["sign_acc_flagged"].append(float(((pred_far & far_t) | (~pred_far & near_t))[fc].mean()))
    lines = ["# T v2 direction diagnostics (192x256, out-of-fit populations)", "",
             "Generated by `python -m scripts.trust_direction_diagnostics`. Contaminated main-scope prompt pixels; "
             "'far' = measured too far (P > 1.05 GT, the upper-bound case), 'near' = P < 0.95 GT. Predicted far = p_far >= p_near. "
             "Image means; '(flagged)' = only pixels the model flags at its threshold.", ""]
    payload = {}
    fm = lambda v: "NA" if not v else f"{np.mean(v):.3f}"
    for ds in TAGS:
        for pop in ("val", "train holdout"):
            rows = [(n, v) for (d, p_, n), v in acc.items() if d == ds and p_ == pop]
            if not rows:
                continue
            lines += [f"## {ds}, {pop}", "", "| Model | far recall | near recall | sign accuracy | far recall (flagged) | "
                      "sign accuracy (flagged) | near share of contaminated |", "|---|---:|---:|---:|---:|---:|---:|"]
            for n, v in rows:
                lines.append(f"| {n} | {fm(v['far_recall'])} | {fm(v['near_recall'])} | {fm(v['sign_acc'])} | "
                             f"{fm(v['far_recall_flagged'])} | {fm(v['sign_acc_flagged'])} | {fm(v['near_share'])} |")
                payload[f"{ds}/{pop}/{n}"] = {k: (float(np.mean(x)) if x else None) for k, x in v.items()}
            lines.append("")
    (ROOT / f"{a.output}.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / f"{a.output}.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
