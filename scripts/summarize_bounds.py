"""R16 items 1-2 tables -> docs/bound_results.md / .json.

Rows: PromptDA-L with the T v1 mask (model threshold and conformal α=0.1 threshold) and with the GT mask,
each without and with the upper-bound cap (flagged prompt that measured too far caps the prediction).
Populations as in summarize_trust: val (out of sample), train-holdout scenes (out of fit), train all.
Also checks that the regenerated HAMMER T v1 cache reproduces the deleted one (prediction hashes).
"""
import json

import scripts.summarize_trust as st
from tp.provenance import ROOT, write_json

st.METHODS = [
    ("PromptDA-L", "promptda_vitl_raw"),
    ("PromptDA-L + Gate mask", "promptda_vitl_gate_prior"),
    ("PromptDA-L + T v1 mask (model thr)", "promptda_vitl_trust_v1_prior"),
    ("PromptDA-L + T v1 mask (model thr), regenerated", "promptda_vitl_trust_v1_prior_regen"),
    ("  + upper-bound cap", "promptda_vitl_trust_v1_prior_cap"),
    ("PromptDA-L + T v1 mask (conformal α=0.1)", "promptda_vitl_trust_v1_crc10_prior"),
    ("  + upper-bound cap", "promptda_vitl_trust_v1_crc10_prior_cap"),
    ("PromptDA-L + GT mask [oracle]", "promptda_vitl_oracle_prior"),
    ("PromptDA-L + GT mask [oracle], train+val cache", "promptda_vitl_oracle_prior_v2"),
    ("  + upper-bound cap [oracle]", "promptda_vitl_oracle_prior_cap"),
    ("  + upper-bound cap [oracle], train+val cache", "promptda_vitl_oracle_prior_v2_cap"),
    ("PromptDA-L + GT mask, cap far-type only (GT sign) [oracle]", "promptda_vitl_oracle_prior_capfar_oracle"),
    ("PromptDA-L + GT mask, cap far-type only (T v2 real_sim_nofeat sign) [oracle mask]", "promptda_vitl_oracle_prior_capfar_t_v2_real_sim_nofeat"),
    ("PromptDA-L + GT mask, cap far-type only (T v2 real_sim sign) [oracle mask]", "promptda_vitl_oracle_prior_capfar_t_v2_real_sim"),
    ("PromptDA-L + T v1 mask, cap far-type only (T v2 real_sim_nofeat sign)", "promptda_vitl_trust_v1_prior_capfar_t_v2_real_sim_nofeat"),
    ("PromptDA-L + T v1 mask, cap far-type only (T v2 real_sim sign)", "promptda_vitl_trust_v1_prior_capfar_t_v2_real_sim"),
]


def reproduction():
    out = {}
    for sp in ("val", "train"):
        a = ROOT / "results" / f"hammer_dev_promptda_vitl_trust_v1_prior_{sp}_v1" / "per_image.json"
        b = ROOT / "results" / f"hammer_dev_promptda_vitl_trust_v1_prior_regen_{sp}_v1" / "per_image.json"
        if a.is_file() and b.is_file():
            ha = {(r["sensor"], r["scene"], r["frame"]): r["prediction_array_sha256"] for r in json.loads(a.read_text())}
            hb = {(r["sensor"], r["scene"], r["frame"]): r["prediction_array_sha256"] for r in json.loads(b.read_text())}
            same = sum(1 for k in ha if hb.get(k) == ha[k])
            out[sp] = dict(images=len(ha), identical_prediction_hashes=same)
    return out


def main():
    lines = ["# R16: upper-bound cap and conformal threshold (development diagnostics)", "",
             "Generated by `python -m scripts.summarize_bounds`. C AbsRel on the main scope; `C full` whole image; "
             "IR / DOR as defined in tp.eval.metrics. Cap: on flagged prompt pixels, prediction = min(prediction, P). "
             "Conformal threshold: α = 0.1, danger = P > 1.2·GT, calibrated on train-holdout scenes "
             "(results/trust_t_v1_crc_d20.json). val and train-holdout are out of fit for T.", ""]
    payload = {}
    head = ["| Method | C AbsRel | C full | IR | DOR | trust AUROC |", "|---|---:|---:|---:|---:|---:|"]
    for ds, (prefix, scope, label) in st.DATA.items():
        for split, hold, tag in (("val", False, "val (out of sample)"), ("train", True, "train holdout scenes (out of fit)"),
                                 ("train", False, "train all (in sample for T)")):
            body, out = st.block(ds, prefix, scope, split, hold)
            if body:
                n = next(iter(out.values()))
                lines += [f"## {label}, {tag}: {n['images']} images / {n['scenes']} scenes", "", *head, *body, ""]
                payload[f"{ds}/{tag}"] = out
    rep = reproduction()
    if rep:
        lines += ["## Reproduction of the deleted HAMMER T v1 PromptDA cache", "",
                  *[f"- {sp}: {v['identical_prediction_hashes']} / {v['images']} predictions bit-identical" for sp, v in rep.items()], ""]
        payload["reproduction"] = rep
    (ROOT / "docs/bound_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/bound_results.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
