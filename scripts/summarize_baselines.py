"""Depth-completion baselines, raw vs + T v1 mask vs GT mask -> docs/baseline_results.md / .json.

Rows: every model in configs/baselines/holm_family_v1.yaml (PromptDA-L from the existing caches, the completion
baselines from cache/bl_*), each with the raw prompt, the T v1 mask (conformal alpha 0.1, deployable) and the GT
mask [oracle]. Populations: val (out of sample) and train-holdout scenes (out of fit for T). Main-scope C AbsRel,
whole-image C, clean-region AbsRel (over-masking shows up here), IR, DOR. Image -> scene -> dataset weighting.
"""
import json

import yaml

from tp.eval.aggregate import aggregate
from tp.provenance import ROOT, write_json
from tp.trust.data import scene_inner_holdout

fmt = lambda v, d=4: "NA" if v is None else f"{v:.{d}f}"
PROMPTDA = [("raw", ["promptda_vitl_raw"]), ("T v1 mask, D_g fill", ["promptda_vitl_trust_v1_crc10_prior"]),
            ("GT mask, D_g fill [oracle]", ["promptda_vitl_oracle_prior", "promptda_vitl_oracle_prior_v2"])]
VAR = [("raw", "raw"), ("T v1 mask", "tmask"), ("GT mask [oracle]", "oracle_mask")]


def row(ds, prefix, scope, run, split, holdout_only):
    base = ROOT / "results" / f"{prefix}_{run}_{split}_v1"
    if not (base / "receipt.json").is_file():
        return None
    stage = json.loads((base / "receipt.json").read_text()).get("stage")
    if stage not in ("small_scale_validation_passed", "completed_with_invalid_predictions"):
        return None
    sc = json.loads((base / f"per_image_{scope}.json").read_text())
    full = json.loads((base / "per_image.json").read_text())
    if holdout_only:
        sc = [r for r in sc if scene_inner_holdout(ds, r["scene"])]
        full = [r for r in full if scene_inner_holdout(ds, r["scene"])]
    if not sc:
        return None
    m = aggregate(sc)["datasets"][ds]["metrics"]; agg = aggregate(full)["datasets"][ds]
    inv = sum(1 for r in full if any(v.get("invalid_count") for v in r["metrics"]["regions"].values()))
    return dict(run=base.name, images=agg["image_count"], scenes=agg["scene_count"], c=m["regions"]["C"]["absrel"],
                c_full=agg["metrics"]["regions"]["C"]["absrel"], clean=m["regions"]["clean"]["absrel"],
                ir=m["IR"]["value"], dor=m["DOR"]["value"], images_with_invalid=inv)


def main():
    spec = yaml.safe_load((ROOT / "configs/baselines/holm_family_v1.yaml").read_text(encoding="utf-8"))
    lines = ["# Depth-completion baselines with and without T v1 (development diagnostics)", "",
             "Generated by `python -m scripts.summarize_baselines`. Main-scope C AbsRel (NYU mirror / HAMMER object pixels), "
             "`C full` whole image, `clean` main-scope pixels whose prompt was correct, IR / DOR as in tp.eval.metrics. "
             "T v1 mask: conformal alpha = 0.1 threshold (method v1). Completion baselines get masked pixels as holes; "
             "PromptDA-L gets them filled with D_g. NA = invalid predictions in that region (never dropped); "
             "`invalid imgs` counts images with any invalid predicted pixel. Statistical tests: docs/holm_plugin_v1.md.", ""]
    payload = {}
    head = ["| Model | Prompt | C AbsRel | C full | clean | IR | DOR | invalid imgs |", "|---|---|---:|---:|---:|---:|---:|---:|"]
    for ds, dd in spec["datasets"].items():
        for split, hold, tag in (("val", False, "val (out of sample)"), ("train", True, "train holdout scenes (out of fit)")):
            body, n = [], None
            for mk, m in spec["models"].items():
                runs = PROMPTDA if mk == "promptda_l" else [(lab, [f"bl_{mk}_{v}"]) for lab, v in VAR]
                for lab, alts in runs:
                    x = next((y for y in (row(ds, dd["prefix"], dd["scope"], r, split, hold) for r in alts) if y), None)
                    if x is None:
                        continue
                    run = x["run"]
                    n = n or x
                    payload[f"{ds}/{tag}/{run}"] = x
                    body.append(f"| {m['label']} | {lab} | {fmt(x['c'])} | {fmt(x['c_full'])} | {fmt(x['clean'])} | "
                                f"{fmt(x['ir'])} | {fmt(x['dor'])} | {x['images_with_invalid']} |")
            if body:
                lines += [f"## {ds}, {tag}: {n['images']} images / {n['scenes']} scenes", "", *head, *body, ""]
    (ROOT / "docs/baseline_results.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(ROOT / "docs/baseline_results.json", dict(stage="development_diagnostic", results=payload))


if __name__ == "__main__":
    main()
